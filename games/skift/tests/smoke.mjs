import {chromium} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto(process.env.SKIFT_URL||'http://127.0.0.1:8787/play/skift/?qa=1');
await page.waitForFunction(()=>window.__SKIFT__,{timeout:30000});
await page.waitForTimeout(1500);
await page.screenshot({path:'evidence/title-desktop.png'});
console.log('TITLE',await page.evaluate(()=>__SKIFT__.snapshot()));
await page.locator('[data-action="start"]').click();
await page.keyboard.down('d');await page.waitForTimeout(600);await page.keyboard.up('d');
await page.keyboard.press('Space');await page.keyboard.press('j');
await page.waitForTimeout(500);await page.screenshot({path:'evidence/play-desktop.png'});
console.log('PLAY',await page.evaluate(()=>__SKIFT__.snapshot()));
await page.keyboard.press('Escape');
await page.screenshot({path:'evidence/pause-desktop.png'});
console.log('ERRORS',errors);
await writeFile('evidence/smoke.json',JSON.stringify({errors,state:await page.evaluate(()=>__SKIFT__.snapshot())},null,2));
await browser.close();
