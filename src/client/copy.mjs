let activeCopy = defaultCopy;
let copyPromise;
const placeholder = /\{([A-Za-z][A-Za-z0-9_]*)\}/g;

function copyFromRuntime(runtime) {
  if (!runtime || typeof runtime !== 'object' || Array.isArray(runtime)) return;
  const next = { ...defaultCopy };
  for (const key of Object.keys(defaultCopy)) {
    if (typeof runtime[key] === 'string') next[key] = runtime[key];
  }
  activeCopy = Object.freeze(next);
}

export function t(key, values = {}) {
  const template = activeCopy[key];
  if (typeof template !== 'string') throw new Error(`Unknown runtime copy key: ${key}`);
  if (!values || typeof values !== 'object' || Array.isArray(values)) throw new TypeError('Interpolation values must be an object');
  return template.replace(placeholder, (match, name) => {
    if (!Object.prototype.hasOwnProperty.call(values, name) || values[name] === null || values[name] === undefined) {
      throw new Error(`Missing runtime copy value: ${name}`);
    }
    return String(values[name]);
  });
}

export async function loadCopy() {
  if (copyPromise) return copyPromise;
  copyPromise = (async () => {
    const preview = globalThis.document?.querySelector?.('#cms-preview-data');
    if (preview) {
      try { copyFromRuntime(JSON.parse(preview.textContent || '{}').runtime); } catch { /* Preview falls back to built-in copy. */ }
      return activeCopy;
    }
    try {
      const response = await fetch('/data/runtime.json', { credentials:'same-origin', referrerPolicy:'no-referrer', signal:AbortSignal.timeout(1500) });
      if (response.ok) copyFromRuntime(await response.json());
    } catch { /* Public runtime copy is optional; built-in copy remains authoritative. */ }
    return activeCopy;
  })();
  return copyPromise;
}
